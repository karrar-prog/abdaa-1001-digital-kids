export const MENTORS_CMS_KEY = 'abdaa_cms_mentors_v4';

// تنظيف النسخ القديمة الافتراضية تلقائياً لضمان ظهور الأسماء والألقاب الرسمية المعتمدة
if (typeof window !== 'undefined') {
  try {
    localStorage.removeItem('abdaa_cms_mentors_v1');
    localStorage.removeItem('abdaa_cms_mentors_v2');
    localStorage.removeItem('abdaa_cms_mentors_v3');
  } catch {
    // ignore
  }
}

export function getActiveMentorsList() {
  if (typeof window === 'undefined') return HONOROLL_MENTORS;
  try {
    const raw = localStorage.getItem(MENTORS_CMS_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    }
  } catch {
    // ignore
  }
  return HONOROLL_MENTORS;
}

export function saveActiveMentorsList(list) {
  if (typeof window === 'undefined') return;
  localStorage.setItem(MENTORS_CMS_KEY, JSON.stringify(list));
  window.dispatchEvent(new CustomEvent('abdaa-cms-updated'));
}

export function resetActiveMentorsList() {
  if (typeof window === 'undefined') return HONOROLL_MENTORS;
  localStorage.removeItem(MENTORS_CMS_KEY);
  localStorage.removeItem('abdaa_cms_mentors_v1');
  window.dispatchEvent(new CustomEvent('abdaa-cms-updated'));
  return HONOROLL_MENTORS;
}
